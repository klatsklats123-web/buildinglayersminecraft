package com.tutorialschematic.camera;

/**
 * Настройка одной дорожки для сборки сцен из {@link BuildAnalyzer.WorkSegment}.
 *
 * <p>Раньше «дробить или нет» решал один общий порог видимости на всех, потом —
 * {@code Granularity}, бинарный выбор «весь материал одним кадром» / «всегда по кускам».
 * Оба подхода были порогами поверх времени, а не описанием того, что дорожка на самом деле
 * должна показать. {@link ScenePlanner} использует эти три числа, чтобы решить, сливать ли
 * соседние участки работы в одну сцену — то есть держать один и тот же ракурс, — или резать.
 *
 * @param mergeAngleTolerance насколько может повернуть фронт (для {@link BuildAnalyzer.Shape#LINEAR}
 *                            участков), прежде чем дорожка сочтёт это сменой стороны и обязана
 *                            резать. Широкий план прощает многое — обошёл угол дома, а всё ещё
 *                            один кадр; крупный план режет почти на каждом повороте.
 * @param maxSceneRadius      сцена не растёт шире этого радиуса, даже если по направлению и форме
 *                            ей ничего не мешает слиться дальше. Без потолка редкий, но широкий
 *                            слой (плоский пол, разреженный экстерьер) дал бы один и тот же
 *                            гигантский кадр что дальнему, что ближнему плану — крупность
 *                            переставала бы что-либо значить.
 * @param minSceneBlocks      меньше стольких блоков сцена не закрывается никаким триггером —
 *                            без этого этажа новому ракурсу физически некуда встать снаружи
 *                            (см. историю с врезанием камеры на крохотных фазах).
 */
public record ShotPolicy(double mergeAngleTolerance, double maxSceneRadius, int minSceneBlocks) {
}
